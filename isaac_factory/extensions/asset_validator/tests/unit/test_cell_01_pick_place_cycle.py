"""Runtime B Phase 3C-tail — physical pick/place cycle with full telemetry.

This is the *tail* of Phase 3C: physical lift already works, but the peg
slips during transport and the world.reset() does not re-snap the peg
to its authored pose (the dynamic rigid body's runtime state survives
across resets in PhysX). Both blockers are closed here using only
PhysX-supported primitives.

What changed vs Phase 3C (initial)
----------------------------------

1. **Deterministic peg reset.** Every cycle, before play resumes, the
   peg is force-snapped via ``RigidPrim.set_world_poses(authored_xyz,
   authored_orientation)`` and both ``set_linear_velocities`` and
   ``set_angular_velocities`` are zeroed. This is a runtime
   initial-condition write — the same kind already applied to the
   UR10e joints — not a teleport during motion.

2. **Full mimic-chain telemetry.** Every Robotiq 2F-140 sub-joint
   (left/right outer knuckle, outer finger, inner finger, inner pad)
   has its measured position sampled at grasp_close end and at the
   transport mid-point, so the mimic propagation can be verified.

3. **Contact telemetry.** PhysX contact-report events are subscribed
   for the duration of every cycle; counts, peak force magnitude (proxy
   via penetration depth × stiffness scalar), grasp-acquire/-lost
   transitions, and peg↔EE relative transform / slip are reported.

4. **No fake attachment, no parenting, no teleport stabilisation, no
   collision disabling, no runtime IK, no online planning.** The
   only mechanical mechanism holding the peg is friction between the
   Robotiq finger pads and the peg, generated by the joint PD drives.

Cycle timing (slowed in YAML vs Phase 3C-initial to reduce transport
instability; the offline joint-space waypoints are unchanged):

  t=0.0   home @ approach_pick; gripper open; peg on belt
  t=2.0   descended to grasp pose; peg in jaws; gripper begins close
  t=2.5   gripper closed (joint PD has converged)
  t=4.0   peg lifted to z = 0.95            (was 3.3; +0.7 s)
  t=7.5   over approach_place               (was 5.8; +1.5 s relative)
  t=9.5   descended to place pose           (was 7.3)
  t=10.0  gripper open / peg released       (was 7.6)
  t=11.0  retracted above placed peg        (was 8.6)
  t=13.5  back home                          (was 11.1)
"""

