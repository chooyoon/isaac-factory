def _build_articulation(world):
    """Initialise the UR10e articulation handle once per test.

    Phase 3I: pass the Xform path (``/World/Robot``) not the joint path.
    The working ``test_articulation_view.py`` examples initialise
    ``Articulation(prim_paths_expr="/World/Franka_[1-2]")`` — the
    articulation root Xform glob, not its child joint. Adding to
    ``world.scene`` is also part of the canonical Isaac Sim flow that
    binds the articulation to the world's physics view.
    """
    import json
    from isaacsim.core.prims import Articulation
    art = Articulation(prim_paths_expr=ROBOT_MOUNT_PATH)
