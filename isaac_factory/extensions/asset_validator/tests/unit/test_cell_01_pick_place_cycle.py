def _print_telemetry(tel: dict) -> None:
    """Human-readable telemetry dump + JSONL sidecar (survives pytest capture)."""
    import json
    keys = (
        "cycle_index", "close_position_rad",
        "peg_xyz_initial", "peg_xyz_at_grasp_close",
        "peg_xyz_at_lift_end", "peg_xyz_at_place", "peg_xyz_final",
        "min_peg_z_world", "max_peg_z_world",
        "peg_in_ee_at_close", "peg_in_ee_max_slip_mm", "peg_in_ee_final_slip_mm",
        "pad_separation_min_m",
        "contact_count_total", "contact_count_peak", "max_penetration_m",
        "grasp_acquired_step", "grasp_lost_step", "peg_drop_step",
    )
    print(f"\n[telemetry cycle={tel['cycle_index']}]")
    for k in keys:
        print(f"    {k}: {tel[k]}")
    print(f"    mimic_joint_pos_at_close:")
    for n, v in tel["mimic_joint_pos_at_close"].items():
        print(f"        {n}: {v}")
    print(f"    mimic_joint_pos_at_lift:")
    for n, v in tel["mimic_joint_pos_at_lift"].items():
        print(f"        {n}: {v}")
    # Persist to JSONL so pytest's stdout capture cannot hide it.
    try:
        Path(_TELEMETRY_JSONL).parent.mkdir(parents=True, exist_ok=True)
        with open(_TELEMETRY_JSONL, "a") as fh:
            fh.write(json.dumps(tel, default=str) + "\n")
    except Exception:                                               # noqa: BLE001
        pass


