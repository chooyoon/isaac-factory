class TestThreeCycleDeterminism:
    """3 full cycles → same peg final pose within 5 mm.

    Each cycle force-resets the peg's runtime pose + velocities via
    RigidPrim.set_world_poses + set_*_velocities. This is the
    Phase 3C-tail determinism fix.
    """

    def test_three_cycles_match(self, world, cell_stage):
        cfg    = _load_cfg()
        player, cfg = _make_player(cell_stage, cfg)
        art,ji = _build_articulation(world)
        peg    = _build_peg_rigid(world)
        cs     = _make_contact_source(cell_stage)
        snaps: list[tuple[float, float, float]] = []
        try:
            for i in range(3):
                tel = _run_full_cycle(
                    world, cell_stage, player, art, ji,
                    peg, cfg, cycle_index=i, contact_source=cs,
                )
                _print_telemetry(tel)
                snaps.append(tel["peg_xyz_final"])
        finally:
            if cs is not None:
                cs.close()

        # Determinism check: cycle 1, 2 vs cycle 0.
        for k in (1, 2):
            for ax, (a, b) in enumerate(zip(snaps[0], snaps[k])):
                delta = abs(a - b)
                assert delta < CYCLE_DETERMINISM_TOL_M, (
                    f"non-deterministic: peg axis {ax} "
                    f"cycle0={a:.6f} cycle{k}={b:.6f} delta={delta:.6f}"
                )
